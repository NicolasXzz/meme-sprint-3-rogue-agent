def _load_fonts():
    """Decode FONT_HEX into [(ascent, descent, {char: glyph}), ...]
    for [bold, regular]. A glyph is (advance, w, h, xoff, yoff, ink)
    where ink is a list of (x, y) ink-pixel coords, xoff/yoff are
    relative to the pen position / baseline at 48px."""
    raw = zlib.decompress(bytes.fromhex(FONT_HEX))
    fonts = []
    off = 0
    for _ in range(2):
        ascent, descent = struct.unpack_from(">Hh", raw, off)
        off += 4
        n = struct.unpack_from(">H", raw, off)[0]
        off += 2
        table = {}
        for _ in range(n):
            cp, adv, w, h, xo, yo, blen = struct.unpack_from(
                ">HHBBbbH", raw, off)
            off += 10
            bits = raw[off:off + blen]
            off += blen
            ink = []
            rb = (w + 7) // 8
            for y in range(h):
                row = bits[y * rb:(y + 1) * rb]
                for x in range(w):
                    if (row[x >> 3] >> (7 - (x & 7))) & 1:
                        ink.append((x, y))
            table[chr(cp)] = (adv, w, h, xo, yo, ink)
        fonts.append((ascent, descent, table))
    return fonts


FONTS = _load_fonts()  # [bold, regular]


def text_width(s, size, bold):
    """Advance-sum width of s at the given size (48px master scaled)."""
    table = FONTS[0 if bold else 1][2]
    sc = size / 48.0
    return sum(table[c][0] * sc for c in s)


def _blit(px, stride, bpp, cw, ch, gx, gy, ink, w, h, sc, pix):
    """Blit one glyph's ink pixels onto bytearray px.

    sc >= 1: each ink pixel becomes a nearest-neighbour block.
    sc <  1: area-average — each output pixel is set when >=30% of
    the source pixels mapping onto it are ink.
    pix is the bytes value of one output pixel (RGB or RGBA)."""
    if sc >= 1.0:
        for (sx, sy) in ink:
            ox0 = gx + int(sx * sc)
            ox1 = gx + int((sx + 1) * sc)
            oy0 = gy + int(sy * sc)
            oy1 = gy + int((sy + 1) * sc)
            if ox1 <= ox0:
                ox1 = ox0 + 1
            if oy1 <= oy0:
                oy1 = oy0 + 1
            ax0 = ox0 if ox0 > 0 else 0
            ax1 = ox1 if ox1 < cw else cw
            if ax1 <= ax0:
                continue
            n = ax1 - ax0
            row = pix * n
            for yy in range(oy0, oy1):
                if 0 <= yy < ch:
                    o = yy * stride + ax0 * bpp
                    px[o:o + n * bpp] = row
    else:
        ow = max(1, int(round(w * sc)))
        oh = max(1, int(round(h * sc)))
        cnt = [0] * (ow * oh)
        area = [0] * (ow * oh)
        for sy in range(h):
            oy = int(sy * sc)
            base = oy * ow
            for sx in range(w):
                area[base + int(sx * sc)] += 1
        for (sx, sy) in ink:
            ox = int(sx * sc)
            oy = int(sy * sc)
            if 0 <= ox < ow and 0 <= oy < oh:
                cnt[oy * ow + ox] += 1
        for oy in range(oh):
            yy = gy + oy
            if yy < 0 or yy >= ch:
                continue
            base = oy * ow
            for ox in range(ow):
                i = base + ox
                if area[i] and cnt[i] * 10 >= area[i] * 3:
                    xx = gx + ox
                    if 0 <= xx < cw:
                        o = yy * stride + xx * bpp
                        px[o:o + bpp] = pix


def draw_text(cv, x, y_top, s, size, bold, color):
    """Draw s on RGB canvas cv; (x, y_top) is the ascender-top-left
    (PIL anchor 'la'), like the original PIL code."""
    ascent, _d, table = FONTS[0 if bold else 1]
    baseline = y_top + int(round(ascent * size / 48.0))
    sc = size / 48.0
    pen = float(x)
    pix = bytes(color)
    for c in s:
        adv, w, h, xo, yo, ink = table[c]
        if ink:
            gx = int(round(pen)) + int(round(xo * sc))
            gy = baseline + int(round(yo * sc))
            _blit(cv.px, cv.stride, 3, W, H, gx, gy, ink, w, h, sc, pix)
        pen += adv * sc


