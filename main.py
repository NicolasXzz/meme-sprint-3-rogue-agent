def _rgba_fill_rounded_rect(buf, bw, bh, x1, y1, x2, y2, r, rgba):
    """Rounded-rect fill on an RGBA bytearray; rgba may be (0,0,0,0)
    to clear (used for the stamp's outline ring)."""
    pix = bytes(rgba)
    stride = bw * 4

    def row(y, xa, xb):
        xa = xa if xa > 0 else 0
        xb = xb if xb < bw else bw
        if xb > xa and 0 <= y < bh:
            o = y * stride + xa * 4
            buf[o:o + (xb - xa) * 4] = pix * (xb - xa)

    for y in range(y1 + r, y2 - r):
        row(y, x1, x2)
    rr = r * r
    for y in range(y1, y1 + r):
        dy = (y1 + r) - y
        dx = int((rr - dy * dy) ** 0.5) if dy < r else 0
        row(y, x1 + r - dx, x2 - r + dx)
    for y in range(y2 - r, y2):
        dy = y - (y2 - r) + 1
        dx = int((rr - dy * dy) ** 0.5) if dy < r else 0
        row(y, x1 + r - dx, x2 - r + dx)


def _rgba_draw_text(buf, bw, bh, x, baseline, s, size, color):
    """Draw s on an RGBA buffer; x is pen start, baseline is the
    baseline y (stamp text is centred by its caller)."""
    _a, _d, table = FONTS[0]  # stamps are always bold
    sc = size / 48.0
    pen = float(x)
    pix = bytes(color) + b"\xff"
    for c in s:
        adv, w, h, xo, yo, ink = table[c]
        if ink:
            gx = int(round(pen)) + int(round(xo * sc))
            gy = baseline + int(round(yo * sc))
            _blit(buf, bw * 4, 4, bw, bh, gx, gy, ink, w, h, sc, pix)
        pen += adv * sc


def make_stamp(text, color, size, pad_x=26, pad_y=14):
    """Rubber-stamp label on a transparent RGBA buffer: coloured
    outline ring + centred bold text. Returns (w, h, buf)."""
    tw = text_width(text, size, True)
    w = int(round(tw)) + pad_x * 2
    h = size + pad_y * 2
    buf = bytearray(w * h * 4)
    _rgba_fill_rounded_rect(buf, w, h, 3, 3, w - 3, h - 3, 12,
                            color + (255,))
    _rgba_fill_rounded_rect(buf, w, h, 8, 8, w - 8, h - 8, 9,
                            (0, 0, 0, 0))
    ascent = FONTS[0][0]
    baseline = h // 2 + int(round(ascent * size / 48.0)) // 2
    _rgba_draw_text(buf, w, h, (w - int(round(tw))) // 2, baseline,
                    text, size, color)
    return w, h, buf


def paste_stamp(cv, stamp, angle_deg, px, py):
    """Rotate stamp by angle_deg (PIL convention: positive =
    counter-clockwise) with expand, bilinear-sample, alpha-composite
    onto the RGB canvas at top-left (px, py)."""
    w, h, buf = stamp
    a = math.radians(angle_deg)
    ca, sa = math.cos(a), math.sin(a)
    nw = int(abs(w * ca) + abs(h * sa)) + 1
    nh = int(abs(w * sa) + abs(h * ca)) + 1
    cx0, cy0 = w / 2.0, h / 2.0
    cx1, cy1 = nw / 2.0, nh / 2.0
    out = cv.px
    stride = cv.stride
    for dy in range(nh):
        oy = py + dy
        if oy < 0 or oy >= H:
            continue
        ry = dy - cy1
        orow = oy * stride
        for dx in range(nw):
            ox = px + dx
            if ox < 0 or ox >= W:
                continue
            rx = dx - cx1
            sx = cx0 + rx * ca - ry * sa
            sy = cy0 + rx * sa + ry * ca
            ix = int(sx)
            iy = int(sy)
            if ix < 0 or iy < 0 or ix + 1 >= w or iy + 1 >= h:
                continue
            fx = sx - ix
            fy = sy - iy
            o00 = (iy * w + ix) * 4
            o10 = o00 + 4
            o01 = o00 + w * 4
            o11 = o01 + 4
            a00 = buf[o00 + 3]
            a10 = buf[o10 + 3]
            a01 = buf[o01 + 3]
            a11 = buf[o11 + 3]
            al = (a00 * (1 - fx) * (1 - fy) + a10 * fx * (1 - fy)
                  + a01 * (1 - fx) * fy + a11 * fx * fy)
            if al < 1.0:
                continue
            al /= 255.0
            r = (buf[o00] * (1 - fx) * (1 - fy) + buf[o10] * fx * (1 - fy)
                 + buf[o01] * (1 - fx) * fy + buf[o11] * fx * fy)
            g = (buf[o00 + 1] * (1 - fx) * (1 - fy)
                 + buf[o10 + 1] * fx * (1 - fy)
                 + buf[o01 + 1] * (1 - fx) * fy + buf[o11 + 1] * fx * fy)
            b = (buf[o00 + 2] * (1 - fx) * (1 - fy)
                 + buf[o10 + 2] * fx * (1 - fy)
                 + buf[o01 + 2] * (1 - fx) * fy + buf[o11 + 2] * fx * fy)
            o = orow + ox * 3
            inv = 1.0 - al
            out[o] = int(r * al + out[o] * inv)
            out[o + 1] = int(g * al + out[o + 1] * inv)
            out[o + 2] = int(b * al + out[o + 2] * inv)


